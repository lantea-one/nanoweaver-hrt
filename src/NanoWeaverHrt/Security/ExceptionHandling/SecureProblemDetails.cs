using System.Text.Json.Serialization;
using System.Xml.Serialization;
using NanoWeaverHrt.Swagger;

namespace NanoWeaverHrt.Security.ExceptionHandling;

/// <summary>
/// RFC 7807 compliant problem details representation delivering descriptive error metadata while strictly preventing sensitive data leakage.
/// </summary>
[XmlRoot("ProblemDetails")]
public sealed class SecureProblemDetails : IExamplesProvider<SecureProblemDetails>
{
    /// <summary>
    /// Gets or sets a URI reference identifying the problem type.
    /// </summary>
    [JsonPropertyName("type")]
    [XmlElement("Type")]
    public string Type { get; set; } = "urn:weaver:error:general";

    /// <summary>
    /// Gets or sets a short, human-readable summary of the problem type.
    /// </summary>
    [JsonPropertyName("title")]
    [XmlElement("Title")]
    public string Title { get; set; } = "An error occurred";

    /// <summary>
    /// Gets or sets the HTTP status code generated by the origin server.
    /// </summary>
    [JsonPropertyName("status")]
    [XmlElement("Status")]
    public int Status { get; set; } = 500;

    /// <summary>
    /// Gets or sets a human-readable explanation specific to this occurrence of the problem.
    /// </summary>
    [JsonPropertyName("detail")]
    [XmlElement("Detail")]
    public string Detail { get; set; } = "An unexpected error occurred.";

    /// <summary>
    /// Gets or sets a URI reference that identifies the specific occurrence of the problem.
    /// </summary>
    [JsonPropertyName("instance")]
    [XmlElement("Instance")]
    public string Instance { get; set; } = "/api";

    /// <summary>
    /// Gets or sets the correlation identifier for tracking this incident in system telemetry.
    /// </summary>
    [JsonPropertyName("traceId")]
    [XmlElement("TraceId")]
    public string TraceId { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the ISO 8601 UTC timestamp when the error occurred.
    /// </summary>
    [JsonPropertyName("timestamp")]
    [XmlElement("Timestamp")]
    public DateTimeOffset Timestamp { get; set; } = DateTimeOffset.UtcNow;

    /// <inheritdoc/>
    public SecureProblemDetails GetExamples()
    {
        return new SecureProblemDetails
        {
            Type = "urn:weaver:error:bad-request",
            Title = "Invalid Request Parameter",
            Status = 400,
            Detail = "The provided username 'admin' is already registered in the sovereign node.",
            Instance = "/api/users",
            TraceId = "0HMV890123:00000001",
            Timestamp = DateTimeOffset.Parse("2026-10-21T12:00:00Z")
        };
    }
}
